// One-off: turns the fascia lettering into SVG paths so the wordmark is identical
// on the page, in og.jpg and in the icons. Run with `node scripts/make-wordmark.mjs`.
import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'node:fs';

const bold = opentype.parse(readFileSync(new URL('./fonts/BarlowCondensed-700.ttf', import.meta.url)).buffer);
const SIZE = 100;
const TRACK = -1.5; // the sign is set tight, like the site's tracking-tight

function layout(font, text, x, y) {
  const cmds = [];
  let pen = x;
  const glyphs = font.stringToGlyphs(text);
  glyphs.forEach((g, i) => {
    cmds.push(...g.getPath(pen, y, SIZE).commands);
    pen += g.advanceWidth * (SIZE / font.unitsPerEm) + TRACK;
    if (i < glyphs.length - 1) pen += font.getKerningValue(g, glyphs[i + 1]) * (SIZE / font.unitsPerEm);
  });
  return { cmds, end: pen - TRACK };
}

function bounds(cmds) {
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  for (const c of cmds) for (const k of ['x', 'y', 'x1', 'y1', 'x2', 'y2']) {
    if (c[k] === undefined) continue;
    if (k.startsWith('x')) { minX = Math.min(minX, c[k]); maxX = Math.max(maxX, c[k]); }
    else { minY = Math.min(minY, c[k]); maxY = Math.max(maxY, c[k]); }
  }
  return { minX, maxX, minY, maxY };
}

const mirror = (cmds, axis) => cmds.map((c) => {
  const m = { ...c };
  for (const k of ['x', 'x1', 'x2']) if (m[k] !== undefined) m[k] = axis * 2 - m[k];
  return m;
});
const shift = (cmds, dx, dy) => cmds.map((c) => {
  const m = { ...c };
  for (const k of ['x', 'x1', 'x2']) if (m[k] !== undefined) m[k] += dx;
  for (const k of ['y', 'y1', 'y2']) if (m[k] !== undefined) m[k] += dy;
  return m;
});
const r = (n) => String(Math.round(n * 10) / 10);
const toD = (cmds) => cmds.map((c) => {
  if (c.type === 'M' || c.type === 'L') return c.type + r(c.x) + ' ' + r(c.y);
  if (c.type === 'Q') return 'Q' + r(c.x1) + ' ' + r(c.y1) + ' ' + r(c.x) + ' ' + r(c.y);
  if (c.type === 'C') return 'C' + r(c.x1) + ' ' + r(c.y1) + ' ' + r(c.x2) + ' ' + r(c.y2) + ' ' + r(c.x) + ' ' + r(c.y);
  return 'Z';
}).join('');

// SHOT reads forwards; CIRCUI is mirrored and hangs off the T, so the word loops back.
const shot = layout(bold, 'SHOT', 0, 0);
const circ = layout(bold, 'CIRCUI', 0, 0);
const cb = bounds(circ.cmds);
const flipped = mirror(circ.cmds, (cb.minX + cb.maxX) / 2);
const fb = bounds(flipped);
const gap = 2.5;
const circPlaced = shift(flipped, shot.end + gap - fb.minX, 0);

const all = [...shot.cmds, ...circPlaced];
const b = bounds(all);
const norm = (cmds) => shift(cmds, -b.minX, -b.minY);

const width = +(b.maxX - b.minX).toFixed(1);
const height = +(b.maxY - b.minY).toFixed(1);

const out = `// Generated by scripts/make-wordmark.mjs from Barlow Condensed Bold (SIL OFL).
// SHOT reads forwards, CIRCUI is mirrored, sharing the T, as painted on the Market Row fascia.
export const WORDMARK = {
  width: ${width},
  height: ${height},
  shot: ${JSON.stringify(toD(norm(shot.cmds)))},
  circui: ${JSON.stringify(toD(norm(circPlaced)))},
} as const;
`;
writeFileSync(new URL('../src/brand/wordmark.ts', import.meta.url), out);
console.log('wordmark', width, height);
